function retention(d, rules = L.retentionRules()) {
  const rows = rules.filter(r => r.action !== "media").map(r => `• ${r.label}: ${r.action === "anonymise" ? "تُفصل عن هويتك" : "تُحذف"} بعد ${r.days} يوماً.`);
  return {
    slug: "retention",
    title: "مدد الاحتفاظ بالبيانات",
    version: "1.0",
    effective: "2026-10-16",
    summary: [
      "لكل نوع من البيانات مدة، وبعدها يُحذف تلقائياً أو يُفصل عن هويتك.",
      "منشوراتك ورسائلك تبقى حتى تحذفها أنت أو تحذف حسابك.",
      "ملفات الوسائط لا تُحذف آلياً إلا إذا فعّل المشغّل ذلك صراحةً."
    ],
    sections: [
      { id: "auto", heading: "ما يُحذف تلقائياً", body: rows },
      {
        id: "content",
        heading: "ما يبقى حتى تحذفه",
        body: L.DATA_MAP.filter(m => m.purpose === "service" && /حتى تحذف/.test(m.retention)).map(m => `• ${m.category}`)
      },
      { id: "kept", heading: "ما نحتفظ به لمدة أطول ولماذا", body: L.RETENTION_EXEMPT.map(e => `• ${e.label}: ${e.why}.`) },
      {
        id: "deletion",
        heading: "عند حذف حسابك",
        body: [
          `بعد مهلة ${d.grace} يوماً تُحذف بيانات الدخول والأجهزة والإعدادات والتفاعلات، ويُمسح نص منشوراتك وتعليقاتك ورسائلك، ويُستبدل اسمك بـ«${L.DELETED_NAME}». تبقى قرارات الإشراف والموافقات وطلباتك مرتبطة بمعرّف داخلي لا يدل عليك.`
        ]
      }
    ]
  };
}

/** all documents for this deployment */
function documents(env = process.env, rules) {
  const d = deployment(env);
  return [terms(d), privacy(d), retention(d, rules)];
}
module.exports = { documents, deployment };
