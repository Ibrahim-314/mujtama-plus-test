const L = require("./compliance-lib");

function deployment(env = process.env) {
  return {
    controller: env.COMPLIANCE_CONTROLLER_NAME || "مجتمع بلس",
    contact: env.COMPLIANCE_CONTACT_EMAIL || null,
    dpo: env.COMPLIANCE_DPO_EMAIL || null,
    hosting: env.COMPLIANCE_HOSTING_REGION || null, // e.g. "المملكة العربية السعودية" or "الاتحاد الأوروبي"
    grace: L.GRACE_DAYS(env)
  };
}
