#!/usr/bin/env python3
"""help-wire: merge help-text/*.json + help-core entries into help-content.js (registry array)."""
import json, re, subprocess, sys
REPO = "/workspace/work/team/help-wire/repo"
SRC = "/workspace/work/team/help-text"
FILES = ["money", "social", "community", "learn-work", "trust"]
LANGS = ["ar", "en"]  # v2.67: the app is Arabic + English only

def lines(v):
    return [x.strip() for x in (v if isinstance(v, list) else str(v or "").split("\n")) if str(x).strip()]

def size(e):  # richness = ar body + tips length
    return len("".join(lines(e["body"].get("ar")))) + len("".join(e.get("tips", {}).get("ar", [])))

def normalize(e, origin):
    e = dict(e)
    m = re.match(r"^(#/[^?]*)\?tab=([\w-]+)$", e["route"])
    if m: e["route"], e["section"] = m.group(1), m.group(2)
    e["body"] = {L: "\n".join(lines(v)) for L, v in e["body"].items() if lines(v)}
    if e.get("tips"): e["tips"] = {L: [t.strip() for t in v if t.strip()][:3] for L, v in e["tips"].items() if v}
    if e.get("aliases"): e["aliases"] = list(dict.fromkeys(e["aliases"]))
    e["_o"] = origin
    return e

# help-core's own entries (read the current array out of the file via node)
core = json.loads(subprocess.check_output(["node", "-e", "global.window={};require(process.argv[1]);console.log(JSON.stringify(window.MPHelpContent))", __import__("os").environ.get("HELP_CORE", "/workspace/work/team/help-wire/help-content.core.js")]))
entries = [normalize(e, "help-core") for e in core]
for f in FILES:
    entries += [normalize(e, f) for e in json.load(open(f"{SRC}/{f}.json"))]


# help-wire extras: router routes the five text files did not cover (found by tools/help-coverage.mjs)
EXTRAS = [{
  "route": "#/transparency/",
  "title": {"ar": "تقارير الشفافية", "en": "Transparency reports"},
  "body": {
    "ar": ["ننشر هنا أرقاماً مجمّعة عن البلاغات وقرارات الإشراف كل شهر وكل ربع سنة.", "افتح أي تقرير لترى أعداد البلاغات حسب النوع والإجراءات المتخذة والاستئنافات.", "التقارير لا تحتوي أي بيانات شخصية."],
    "en": ["Aggregated numbers on reports and moderation decisions, published every month and every quarter.", "Open a report to see reports by type, the actions taken and the appeals.", "Reports never contain personal data."]},
  "tips": {
    "ar": ["«نسخة للمشاركة» تفتح رابطاً عاماً للتقرير يمكنك إرساله لأي أحد."],
    "en": ["“Shareable copy” opens a public link to the report that you can send to anyone."]}
}]
entries += [normalize(e, "help-wire") for e in EXTRAS]

merged, log = {}, []
for e in entries:
    k = (e["route"], e.get("section", ""))
    if k not in merged: merged[k] = e; continue
    a, b = merged[k], e
    keep, other = (a, b) if size(a) >= size(b) else (b, a)
    out = dict(keep)
    al = list(dict.fromkeys((a.get("aliases") or []) + (b.get("aliases") or [])))
    if al: out["aliases"] = al
    tips = {}
    for L in LANGS:
        t = list(dict.fromkeys((keep.get("tips", {}).get(L) or []) + (other.get("tips", {}).get(L) or [])))[:3]
        if t: tips[L] = t
    if tips: out["tips"] = tips
    out["_o"] = keep["_o"] + "+" + other["_o"]
    merged[k] = out
    log.append(f"dup {k}: kept {keep['_o']} body, merged {other['_o']} aliases/tips")

# an alias that is another entry's route would shadow nothing (same score) but is confusing → drop it
routes = {r for r, _ in merged}
for e in merged.values():
    if e.get("aliases"):
        e["aliases"] = [a for a in e["aliases"] if a not in routes or a == e["route"]] or None
        if not e["aliases"]: e.pop("aliases")

order = ["route", "section", "aliases", "title", "body", "tips"]
arr = [{k: e[k] for k in order if k in e} for e in merged.values()]
head = open(__import__("os").environ.get("HELP_CORE", "/workspace/work/team/help-wire/help-content.core.js")).read().split("window.MPHelpContent")[0]
head = head.replace("/* مجتمع بلس — page-help registry (v2.61, lazy chunk \"helpcontent\", loaded by help-ui.js the first time a page head is drawn).",
  "/* مجتمع بلس — page-help registry (v2.61). GENERATED by help-wire build_registry.py from help-text/*.json — edit the JSON and re-run.\n"
  " * Split per language to keep each lazy chunk small: this file (chunk \"helpcontent\") holds every entry's route/section/aliases and the\n"
  " * Arabic text; help-content-{en,fr,ur}.js (chunks \"helpcontent-<lang>\") hold { \"route|section\": {title, body, tips} } for that\n"
  " * language and are merged in by help-ui.js only when the interface is in that language (Arabic stays the fallback).\n"
  " * Optional \"section\": one page with inner sections — #/cadmin/:id reads ?s=, #/c/:id the active tab (posts / channels when a channel\n"
  " * is open), #/studio the active studio tab; an entry with a matching section wins over the section-less one.")
head = head.replace("(other agents: append entries to the array below, keep it valid plain JS, no functions)", "(preferably add it to help-text/*.json and re-run the generator; a hand-added entry also works — keep it plain JS, and put en/fr/ur in help-content-<lang>.js under \"route|section\")")
def pick(e, L):
    o = {}
    for f in ("title", "body", "tips"):
        if e.get(f) and L in e[f]: o[f] = e[f][L]
    return o
key = lambda e: e["route"] + "|" + e.get("section", "")
ar = []
for e in arr:
    x = {k: e[k] for k in ("route", "section", "aliases") if k in e}
    x.update({f: {"ar": e[f]["ar"]} for f in ("title", "body", "tips") if e.get(f) and "ar" in e[f]})
    ar.append(x)
body = ",\n".join("  " + json.dumps(x, ensure_ascii=False, separators=(",", ":")) for x in ar)
open(REPO + "/help-content.js", "w").write(head + "window.MPHelpContent = [\n" + body + "\n];\n")
for L in ("en",):
    rows = ",\n".join("  " + json.dumps(key(e), ensure_ascii=False) + ":" + json.dumps(pick(e, L), ensure_ascii=False, separators=(",", ":")) for e in arr if pick(e, L))
    open(f"{REPO}/help-content-{L}.js", "w").write(f"/* مجتمع بلس — page help, {L} text (GENERATED by help-wire build_registry.py; lazy chunk \"helpcontent-{L}\", merged by help-ui.js). */\n(window.MPHelpContentL = window.MPHelpContentL || {{}}).{L} = {{\n{rows}\n}};\n")
print(len(arr), "entries;", len(log), "duplicates merged"); print("\n".join(log))
